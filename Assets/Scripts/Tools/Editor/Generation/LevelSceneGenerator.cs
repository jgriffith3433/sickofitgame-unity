#if UNITY_EDITOR
using UnityEngine;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine.SceneManagement;
using SickOfIt.Data;
using SickOfIt.Data.Config;
using SickOfIt.Core.Progression;

namespace SickOfIt.Tools.Editor.Generation
{
    /// <summary>
    /// Generates a level scene from LevelConfig.
    /// 
    /// The generated scene is minimal — just the structural skeleton.
    /// LevelRuntime does the actual spawning at runtime from config.
    /// 
    /// Scene structure:
    ///   - SceneRoot (SceneContentController, SpriteFrameLoadWaiter)
    ///     - Backgrounds/ (PlayableDirectors for sprite frame playback)
    ///     - Player (Character prefab instance)
    ///     - Level (ground collider, boundaries)
    ///     - UI/ (mobile controls, HUD)
    ///     - LevelCompletion (PlayableDirector for end sequence)
    /// 
    /// IMPORTANT: Prefabs must be generated BEFORE calling this generator.
    /// Run ProjectilePrefabGenerator, PlayerPrefabGenerator, EnemyPrefabGenerator first.
    /// </summary>
    public static class LevelSceneGenerator
    {
        private const string SCENES_ROOT = "Assets/Scenes";
        
        // Projectile prefab paths (generated by ProjectilePrefabGenerator)
        private const string PLAYER_PROJECTILE_PATH = "Assets/Prefabs/Combat/Projectile_Player.prefab";
        private const string ENEMY_PROJECTILE_PATH = "Assets/Prefabs/Combat/Projectile_Enemy.prefab";
        private const string LASER_PROJECTILE_PATH = "Assets/Prefabs/Combat/Projectile_Laser.prefab";

        public static bool GenerateLevelScene(GameDefinition gd)
        {
            if (gd == null)
            {
                Debug.LogError("[LevelGen] Null GameDefinition!");
                return false;
            }

            // Validate that required prefabs exist
            if (gd.player?.playerPrefab == null)
            {
                Debug.LogError("[LevelGen] No playerPrefab in GameDefinition! Run PlayerPrefabGenerator first.");
                return false;
            }

            Debug.Log("Generating Level.unity...");
            string scenePath = $"{SCENES_ROOT}/Level.unity";

            // Create or open scene
            var scene = EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Single);

            // Create scene root
            var sceneRoot = new GameObject("SceneRoot");

            // Add SceneContentController for addressable loading
            var contentController = sceneRoot.AddComponent<SickOfIt.Core.Flow.SceneContentController>();

            // Create content parent (everything under here gets hidden/shown by SceneContentController)
            var content = new GameObject("Content");
            content.transform.SetParent(sceneRoot.transform);

            // Backgrounds container
            var backgrounds = new GameObject("Backgrounds");
            backgrounds.transform.SetParent(content.transform);

            // Player spawn point — uses first level config's position, or default
            var playerSpawnPos = new Vector3(-4f, 0f, 0f);
            if (gd.levels.Count > 0)
                playerSpawnPos = new Vector3(gd.levels[0].playerSpawnPosition.x, gd.levels[0].playerSpawnPosition.y, 0f);

            var playerSpawn = new GameObject("PlayerSpawn");
            playerSpawn.transform.SetParent(content.transform);
            playerSpawn.transform.position = playerSpawnPos;

            // Instantiate player Character prefab from GameDefinition (REQUIRED)
            GameObject player = (GameObject)PrefabUtility.InstantiatePrefab(gd.player.playerPrefab, content.transform);
            player.name = "Character";
            player.transform.position = playerSpawnPos;

            // Ground / boundaries
            var level = new GameObject("Level");
            level.transform.SetParent(content.transform);

            // Ground collider — position & size from config
            var ground = new GameObject("Ground");
            ground.transform.SetParent(level.transform);
            ground.transform.position = new Vector3(0f, gd.groundY, 0f);
            var groundCollider = ground.AddComponent<BoxCollider2D>();
            groundCollider.size = gd.groundColliderSize;
            int groundLayer = LayerMask.NameToLayer("Ground");
            if (groundLayer >= 0) ground.layer = groundLayer;

            // Left wall
            var leftWall = new GameObject("LeftWall");
            leftWall.transform.SetParent(level.transform);
            leftWall.transform.position = new Vector3(-gd.wallX, 0f, 0f);
            var leftCollider = leftWall.AddComponent<BoxCollider2D>();
            leftCollider.size = gd.wallColliderSize;

            // Right wall
            var rightWall = new GameObject("RightWall");
            rightWall.transform.SetParent(level.transform);
            rightWall.transform.position = new Vector3(gd.wallX, 0f, 0f);
            var rightCollider = rightWall.AddComponent<BoxCollider2D>();
            rightCollider.size = gd.wallColliderSize;

            // Win zone bounds are set directly on LevelRuntime (no separate trigger script)

            // Music AudioSource
            var musicGo = new GameObject("Music");
            musicGo.transform.SetParent(content.transform);
            var audioSource = musicGo.AddComponent<AudioSource>();
            audioSource.playOnAwake = false;
            audioSource.loop = true;

            // Camera from prefab
            Camera sceneCamera = null;
            if (gd.levelCameraPrefab != null)
            {
                var cameraGo = (GameObject)PrefabUtility.InstantiatePrefab(gd.levelCameraPrefab);
                cameraGo.name = "Main Camera";
                cameraGo.tag = "MainCamera";
                cameraGo.transform.SetParent(sceneRoot.transform);
                sceneCamera = cameraGo.GetComponent<Camera>();
                if (sceneCamera != null)
                    sceneCamera.orthographicSize = gd.levelCameraOrthoSize;
            }
            else
            {
                var cameraGo = new GameObject("Main Camera");
                cameraGo.transform.SetParent(sceneRoot.transform);
                cameraGo.tag = "MainCamera";
                var cam = cameraGo.AddComponent<Camera>();
                cam.orthographic = true;
                cam.orthographicSize = gd.levelCameraOrthoSize;
                cameraGo.AddComponent<AudioListener>();
                sceneCamera = cam;
            }

            // Place full UI prefab (MobileController) from GameDefinition
            GameObject mobileController = null;
            if (gd.levelUIPrefab != null)
            {
                mobileController = (GameObject)PrefabUtility.InstantiatePrefab(gd.levelUIPrefab);
                mobileController.name = "MobileController";
                mobileController.transform.SetParent(content.transform);
                WireCanvasCamera(mobileController, sceneCamera);
                Debug.Log("[LevelGen] Placed level UI prefab");
            }

            // Add LevelRuntime directly to the scene and wire references
            var levelRuntimeGo = new GameObject("LevelRuntime");
            levelRuntimeGo.transform.SetParent(sceneRoot.transform);
            var levelRuntime = levelRuntimeGo.AddComponent<LevelRuntime>();
            var lrso = new SerializedObject(levelRuntime);
            if (player != null) lrso.FindProperty("characterObject").objectReferenceValue = player;
            lrso.FindProperty("playerSpawnPoint").objectReferenceValue = playerSpawn.transform;
            lrso.FindProperty("musicSource").objectReferenceValue = audioSource;

            // Win zone bounds — LevelRuntime reads per-level config at runtime,
            // but we set defaults from the first level for the generated scene
            var defaultWinCenter = new Vector2(6.5f, 0f);
            var defaultWinHalfSize = new Vector2(0.5f, 4f);
            if (gd.levels.Count > 0)
            {
                defaultWinCenter = gd.levels[0].winZoneCenter;
                defaultWinHalfSize = gd.levels[0].winZoneHalfSize;
            }
            lrso.FindProperty("winZoneCenter").vector2Value = defaultWinCenter;
            lrso.FindProperty("winZoneHalfSize").vector2Value = defaultWinHalfSize;

            // ── Create projectile pools (sizes from config) ──
            var poolContainer = new GameObject("Pools");
            poolContainer.transform.SetParent(sceneRoot.transform);

            int playerPoolSize = gd.GetProjectileConfig("Player")?.poolSize ?? 10;
            int enemyPoolSize = gd.GetProjectileConfig("Enemy")?.poolSize ?? 20;
            int laserPoolSize = gd.GetProjectileConfig("Laser")?.poolSize ?? 5;

            var playerPoolGo = CreatePool(poolContainer.transform, "PlayerProjectilePool", PLAYER_PROJECTILE_PATH, playerPoolSize);
            var enemyPoolGo = CreatePool(poolContainer.transform, "EnemyProjectilePool", ENEMY_PROJECTILE_PATH, enemyPoolSize);
            var laserPoolGo = CreatePool(poolContainer.transform, "LaserPool", LASER_PROJECTILE_PATH, laserPoolSize);

            if (playerPoolGo != null)
                lrso.FindProperty("playerProjectilePool").objectReferenceValue = playerPoolGo.GetComponent<SickOfIt.Core.ObjectPool>();
            if (enemyPoolGo != null)
                lrso.FindProperty("enemyProjectilePool").objectReferenceValue = enemyPoolGo.GetComponent<SickOfIt.Core.ObjectPool>();
            if (laserPoolGo != null)
                lrso.FindProperty("laserPool").objectReferenceValue = laserPoolGo.GetComponent<SickOfIt.Core.ObjectPool>();

            lrso.ApplyModifiedPropertiesWithoutUndo();

            // ── Discover mobile controls from MobileController hierarchy ──
            MobileControllerFramework.Analog moveAnalog = null;
            MobileControllerFramework.Analog fireAnalog = null;
            MobileControllerFramework.Button rewindBtn = null;
            SickOfIt.Core.Input.GameInputManager gim = null;

            if (mobileController != null)
            {
                // Analogs are named "(Prb)MoveAnalog" and "(Prb)FireAnalog" in the prefab
                foreach (var analog in mobileController.GetComponentsInChildren<MobileControllerFramework.Analog>(true))
                {
                    if (analog.gameObject.name.Contains("Move"))
                        moveAnalog = analog;
                    else if (analog.gameObject.name.Contains("Fire"))
                        fireAnalog = analog;
                }

                // Take the first enabled Button component as the rewind button
                foreach (var btn in mobileController.GetComponentsInChildren<MobileControllerFramework.Button>(true))
                {
                    if (btn.enabled)
                    {
                        rewindBtn = btn;
                        break;
                    }
                }

                gim = mobileController.GetComponentInChildren<SickOfIt.Core.Input.GameInputManager>(true);
            }

            // Discover HealthUI from UI hierarchy and wire to LevelRuntime
            SickOfIt.Combat.Health.HealthUI healthUI = null;
            if (mobileController != null)
                healthUI = mobileController.GetComponentInChildren<SickOfIt.Combat.Health.HealthUI>(true);
            if (healthUI != null)
            {
                lrso.Update();
                lrso.FindProperty("healthUI").objectReferenceValue = healthUI;
                lrso.ApplyModifiedPropertiesWithoutUndo();
            }

            // Wire mobile controls + camera directly into PlayerController
            if (player != null)
            {
                var pc = player.GetComponentInChildren<SickOfIt.Core.Input.PlayerController>();
                if (pc != null)
                {
                    var pcSo = new SerializedObject(pc);
                    if (sceneCamera != null)
                        pcSo.FindProperty("mainCamera").objectReferenceValue = sceneCamera;
                    if (moveAnalog != null)
                        pcSo.FindProperty("moveAnalog").objectReferenceValue = moveAnalog;
                    if (fireAnalog != null)
                        pcSo.FindProperty("fireAnalog").objectReferenceValue = fireAnalog;
                    if (gim != null)
                        pcSo.FindProperty("gameInputManager").objectReferenceValue = gim;
                    pcSo.ApplyModifiedPropertiesWithoutUndo();
                    Debug.Log("[LevelGen] Wired mobile controls → PlayerController");
                }
            }

            // Add GameClock (pre-attached so LevelRuntime doesn't AddComponent at runtime)
            levelRuntimeGo.AddComponent<SickOfIt.Core.GameClock>();

            // Add RewindTimeline + RewindController and wire their references
            var rewindTimeline = levelRuntimeGo.AddComponent<SickOfIt.Core.Rewind.RewindTimeline>();

            // Wire RewindTimeline config values from GameDefinition
            var rtSo = new SerializedObject(rewindTimeline);
            rtSo.FindProperty("recordInterval").floatValue = gd.rewindRecordInterval;
            rtSo.FindProperty("maxHistorySeconds").floatValue = gd.rewindMaxHistorySeconds;
            rtSo.ApplyModifiedPropertiesWithoutUndo();

            var rewindController = levelRuntimeGo.AddComponent<RewindController>();
            var rcso = new SerializedObject(rewindController);
            rcso.FindProperty("musicSource").objectReferenceValue = audioSource;
            rcso.FindProperty("rewindSpeed").floatValue = gd.player.rewindSpeed;
            rcso.FindProperty("minimumTimeBeforeRewind").floatValue = gd.player.minimumTimeBeforeRewind;
            if (rewindBtn != null)
                rcso.FindProperty("rewindButton").objectReferenceValue = rewindBtn;
            rcso.ApplyModifiedPropertiesWithoutUndo();
            Debug.Log($"[LevelGen] Wired RewindController (rewindButton: {rewindBtn != null})");

            // ── Create pickup pool ──
            string pickupPrefabPath = "Assets/Prefabs/Combat/Diamond.prefab";
            int pickupPoolSize = gd.pickupConfig?.poolSize ?? 20;
            var pickupPoolGo = CreatePool(poolContainer.transform, "PickupPool", pickupPrefabPath, pickupPoolSize);
            if (pickupPoolGo != null)
            {
                lrso.Update();
                lrso.FindProperty("pickupPool").objectReferenceValue = pickupPoolGo.GetComponent<SickOfIt.Core.ObjectPool>();
                lrso.ApplyModifiedPropertiesWithoutUndo();
            }

            // Set the contentRoots via SerializedObject
            var so = new SerializedObject(contentController);
            var contentRoots = so.FindProperty("contentRoots");
            contentRoots.arraySize = 1;
            contentRoots.GetArrayElementAtIndex(0).objectReferenceValue = content;
            so.ApplyModifiedPropertiesWithoutUndo();

            // Save scene
            EditorSceneManager.SaveScene(scene, scenePath);

            Debug.Log($"[LevelGen] Generated scene: {scenePath}");

            return true;
        }
        
        private static void WireCanvasCamera(GameObject uiRoot, Camera camera)
        {
            if (uiRoot == null || camera == null) return;
            foreach (var canvas in uiRoot.GetComponentsInChildren<Canvas>(true))
            {
                if (canvas.renderMode == RenderMode.ScreenSpaceCamera)
                    canvas.worldCamera = camera;
            }
        }

        /// <summary>
        /// Create an ObjectPool GameObject with a prefab and initial size.
        /// Returns null if the prefab can't be loaded.
        /// </summary>
        private static GameObject CreatePool(Transform parent, string poolName, string prefabPath, int initialSize)
        {
            var prefab = AssetDatabase.LoadAssetAtPath<GameObject>(prefabPath);
            if (prefab == null)
            {
                Debug.LogWarning($"[LevelGen] Pool prefab not found: {prefabPath}");
                return null;
            }

            var go = new GameObject(poolName);
            go.transform.SetParent(parent);
            var pool = go.AddComponent<SickOfIt.Core.ObjectPool>();

            var poolSo = new SerializedObject(pool);
            poolSo.FindProperty("prefab").objectReferenceValue = prefab;
            poolSo.FindProperty("initialSize").intValue = initialSize;
            poolSo.ApplyModifiedPropertiesWithoutUndo();

            Debug.Log($"[LevelGen] Created pool '{poolName}' ({prefabPath}, size={initialSize})");
            return go;
        }
    }
}
