using System;
using System.Collections.Generic;
using UnityEngine;

namespace SickOfIt.Data.Config
{
    /// <summary>
    /// All player-related configuration.
    /// PlayerController and UpgradeShopManager read from this at runtime.
    /// PlayerPrefabGenerator uses this to create the Character prefab.
    /// </summary>
    [Serializable]
    public class PlayerConfig
    {
        [Header("Prefab (set by generator)")]
        [Tooltip("The player character prefab to spawn in levels (generated by PlayerPrefabGenerator)")]
        public GameObject playerPrefab;

        [Header("Sprite/Animation (for generator)")]
        [Tooltip("Sprite sheet for player animations (sliced in Multiple mode). Used as fallback for states that don't specify their own sheet.")]
        public Texture2D spriteSheet;
        [Tooltip("Animation frames per second")]
        public int animationFps = 12;
        [Tooltip("Scale multiplier for the Graphics child")]
        public float spriteScale = 0.25f;

        [Header("Animation Config (for generator)")]
        [Tooltip("Full animation setup: states, transitions, parameters, events. If set, the generator builds a multi-state animator. If null, falls back to a single idle clip from spriteSheet.")]
        public AnimationConfig animationConfig;
        [Tooltip("Shadow sprite to place under the player")]
        public Sprite shadowSprite;

        [Header("Movement")]
        public float moveSpeed = 2f;
        public float jumpForce = 9f;
        public float gravityScale = 1.8f;
        public float groundCheckDistance = 0.2f;
        public float groundCheckWidth = 0.1f;

        [Header("Combat")]
        public bool enableShooting = true;
        public float fireRate = 0.25f;
        public float projectileSpeed = 10f;
        public float projectileLifetime = 5f;
        [Tooltip("Rotate each shot to face where it flies.")]
        public bool projectileFaceAim = false;
        [Tooltip("Direction (degrees, 0 = right, 90 = up) the projectile art travels in when unrotated.")]
        public float projectileSpriteAngle = 0f;
        [Tooltip("Where shots leave the weapon, relative to the player's center in world units (facing right); x is mirrored when aiming left.")]
        public Vector2 projectileSpawnOffset = new Vector2(0.5f, 0f);
        [Tooltip("The aim guide: a faint laser line from the muzzle along each shot his next volley fires.")]
        public AimGuideConfig aimGuide = new AimGuideConfig();

        [Header("Physics")]
        public float colliderRadius = 0.3f;

        [Header("Combat - Invincibility")]
        public bool hasInvincibilityFrames = true;
        public float invincibilityDuration = 0.5f;

        [Header("Movement - Platform")]
        public float dropThroughForce = 5f;
        [Tooltip("How far down the keyboard/gamepad must press to drop through a one-way platform (-1 = full down)")]
        public float dropThroughThreshold = -0.75f;
        [Tooltip("Drop-through only counts within this many degrees of straight down, so a run with the stick a little low never drops")]
        public float dropThroughMaxAngle = 30f;
        [Tooltip("Seconds of continuous down on a one-way platform before he drops; letting go starts it over")]
        public float dropThroughHoldSeconds = 0.18f;

        [Header("Movement - Rotation")]
        [Tooltip("If true, use 2D sprite flip (localScale.x) instead of Y-axis rotation")]
        public bool use2DFlip = true;
        public float normalRotationSpeed = 900f;
        public float firingRotationSpeed = 1800f;

        [Header("Shadow")]
        public Vector3 shadowOffset = new Vector3(0, -0.4f, 0);
        public Color shadowColor = new Color(0, 0, 0, 0.5f);
        [Tooltip("Sprite sheet for shadow animation")]
        public Texture2D shadowSpriteSheet;
        [Tooltip("Shadow animation FPS")]
        public int shadowAnimationFps = 12;
        [Tooltip("Maximum height at which shadow is still visible")]
        public float shadowMaxHeight = 10f;
        [Tooltip("Minimum scale of shadow when at max height")]
        public float shadowMinScale = 0.2f;
        [Tooltip("How far down to raycast for ground detection")]
        public float shadowRaycastDistance = 20f;

        [Header("Input")]
        [Tooltip("Minimum stick deflection to register movement")]
        public float inputDeadzone = 0.1f;
        [Tooltip("How far down the move touch must be pulled to drop through a one-way platform")]
        public float mobileDropThreshold = -0.75f;
        [Tooltip("Downward velocity threshold for falling detection")]
        public float jumpDetectVelocityThreshold = 0.3f;

        [Header("Audio - SFX")]
        [Tooltip("Sound played when the player takes damage")]
        public AudioClip[] hurtSounds;
        [Tooltip("Sound played when the player dies")]
        public AudioClip[] deathSounds;
        [Tooltip("Sound played when the player jumps")]
        public AudioClip jumpSound;
        [Tooltip("Sound played when the player fires a projectile")]
        public AudioClip fireSound;
        [Tooltip("Sound played when the player lands on ground")]
        public AudioClip landSound;
        [Range(0f, 0.3f)]
        [Tooltip("Random pitch variation for SFX")]
        public float pitchVariation = 0.1f;

        [Header("Rewind")]
        public float rewindSpeed = 3f;
        public float minimumTimeBeforeRewind = 2f;
        [Tooltip("How long the rewind button must be held before video and death scenes rewind.")]
        public float rewindHoldSeconds = 0.22f;
        [Tooltip("Seconds after a lethal hit during which a rewind can cancel the death scene.")]
        public float deathRewindGrace = 0.6f;
        [Tooltip("With rewind juice left, how long a death waits (\"Hold R to undo it!\") before the death scene.")]
        public float deathRewindWindow = 2.5f;

        [Header("Hurt Flash")]
        public Color hurtFlashColor = new Color(1f, 0.2f, 0.2f, 1f);
        public int hurtFlashCount = 2;
        public float hurtFlashOnDuration = 0.08f;
        public float hurtFlashOffDuration = 0.06f;
        [Range(0f, 1f)]
        public float hurtFlashIntensity = 0.5f;

        [Header("Roguelite")]
        public int baseMaxHealth = 5;
        public int maxExtraJumps = 2;
        public int extraJumpCost = 100;

        [Header("Upgrades")]
        public List<UpgradeDefinition> availableUpgrades = new List<UpgradeDefinition>();
    }

    /// <summary>
    /// The aim guide (AimGuide): one thin, see-through line per shot of the next volley, drawn from the muzzle in the
    /// direction the shot will fly. Presentation only.
    /// </summary>
    [Serializable]
    public class AimGuideConfig
    {
        [Tooltip("Draw the guide at all.")]
        public bool enabled = true;
        [Tooltip("Line colour (its alpha is ignored: see alpha).")]
        public Color color = new Color(1f, 0.85f, 0.45f, 1f);
        [Tooltip("Opacity at the muzzle of the main shot's line (it fades out to nothing at its tip).")]
        public float alpha = 0.4f;
        [Tooltip("Opacity at the muzzle of the extra shots' lines (spread upgrades), fainter than the main one.")]
        public float extraShotAlpha = 0.22f;
        [Tooltip("Length as a fraction of the screen's short side.")]
        public float length = 0.16f;
        [Tooltip("Thickness as a fraction of the screen's short side.")]
        public float width = 0.004f;
        [Tooltip("Draw order in the Player band; below 0 keeps it under platforms, hazards, enemies, pickups and bullets.")]
        public int sortingOrder = -1;
    }

    /// <summary>
    /// Defines one purchasable upgrade in the shop.
    /// </summary>
    [Serializable]
    public class UpgradeDefinition
    {
        public string id;
        public string title;
        public string description;
        [Tooltip("Diamonds for each level, in order (the last price repeats).")]
        public int[] costsPerLevel;
        public int maxLevel;
        [Tooltip("What each level does.")]
        public ShopEffect effect = ShopEffect.None;
        [Tooltip("How much each level adds: health points, air jumps, seconds of rewind, magnet range, or a fraction (0.1 = +10%) for speed, fire rate and damage.")]
        public float amountPerLevel = 1f;
        [Tooltip("Hidden from Yooba's shop until every condition holds: flag:<id>, weapon:<id>, shop:<id>[:level], grudge:<id>[:level], level:<n> (Requirements). Empty = always for sale. A good already owned is never hidden.")]
        public List<string> requires = new List<string>();

        /// <summary>For sale: owned already (a save from before the gate keeps its goods) or every requirement met.</summary>
        public bool IsForSale(int ownedLevel) => ownedLevel > 0 || SickOfIt.Data.Requirements.Met(requires);

        /// <summary>The effect, treating the original "extraJump" entry (written before effects existed) as ExtraJump.</summary>
        public ShopEffect Effect => effect == ShopEffect.None && id == "extraJump" ? ShopEffect.ExtraJump : effect;
    }

    /// <summary>What a shop upgrade does per level.</summary>
    public enum ShopEffect
    {
        None,
        [Tooltip("+amount max health (kept between levels).")] MaxHealth,
        [Tooltip("+amount air jumps.")] ExtraJump,
        [Tooltip("+amount x100% move speed.")] MoveSpeed,
        [Tooltip("+amount x100% fire rate.")] FireRate,
        [Tooltip("+amount x100% damage.")] Damage,
        [Tooltip("+amount seconds of rewind juice (max and starting).")] RewindJuice,
        [Tooltip("+amount world units of pickup magnet range.")] Magnet,
        [Tooltip("+amount x100% damage for melee weapons (fists) only.")] MeleeDamage,
        [Tooltip("+amount x100% reach for melee weapons (fists) only.")] MeleeReach,
        [Tooltip("Any level: the weapons he holds survive the end of a run (WeaponProgress is not cleared).")] KeepWeapons,
    }
}
